"""Keep native generated originals and export only downscaled responsive WebP files."""
import json
import shutil
import pprint
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
specs = json.loads((ROOT / 'docs/generated-assets.json').read_text())
out = ROOT / 'static/images/media'
originals = ROOT / 'docs/assets/generated'
out.mkdir(parents=True, exist_ok=True)
originals.mkdir(parents=True, exist_ok=True)
manifest = {}
for spec in specs:
    name = spec['name']
    source = Path(spec['generated_file'])
    destination = originals / f'{name}.png'
    if source.exists() and source.resolve() != destination.resolve():
        shutil.copyfile(source, destination)
    image = Image.open(destination).convert('RGB')
    width, height = image.size
    variants = []
    for size in sorted(set([s for s in (320, 640, 960, 1440) if s < width] + [width])):
        filename = f'{name}-{size}.webp'
        image.resize((size, round(height * size / width)), Image.Resampling.LANCZOS).save(out / filename, quality=88, method=6)
        variants.append({'width': size, 'file': 'images/media/' + filename})
    manifest[name] = {'width': width, 'height': height, 'generated': True, 'variants': variants}
    spec['generated_file'] = 'docs/assets/generated/' + name + '.png'
    spec['actual_size'] = [width, height]
for source in (ROOT / 'static/images').glob('*'):
    if source.suffix.lower() not in ('.jpg', '.png', '.webp'):
        continue
    with Image.open(source) as image:
        width, height = image.size
    manifest[source.name] = {'width': width, 'height': height, 'generated': False,
                             'variants': [{'width': width, 'file': 'images/' + source.name}]}
(ROOT / 'docs/generated-assets.json').write_text(json.dumps(specs, indent=2) + '\n')
(ROOT / 'website/image_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
(ROOT / 'website/image_manifest.py').write_text('# Generated by tools/build_responsive_assets.py\nMANIFEST = ' + pprint.pformat(manifest, sort_dicts=False) + '\n')
print({name: [item['width'], item['height']] for name, item in manifest.items()})
